function verify_paper_results()
%VERIFY_PAPER_RESULTS Validate a generated run against the paper.

root_directory = fileparts(mfilename('fullpath'));
metrics_file = fullfile(root_directory,'results','pcac_quadrotor_metrics.csv');
expected_file = fullfile(root_directory,'validation','paper_expected_metrics.csv');

check_required(exist(metrics_file,'file') == 2, ...
    'Generated metrics file exists. Run main_pcac_quadrotor first.');
check_required(exist(expected_file,'file') == 2, ...
    'Tracked paper expectations exist.');

actual = readtable(metrics_file,'TextType','string','VariableNamingRule','preserve');
expected = readtable(expected_file,'TextType','string','VariableNamingRule','preserve');

required_columns = ["Case","Method","Coefficients","PositionRMSE_m", ...
    "FinalMassError_kg","FinalTrimError_N","PredictionPositionRMSE", ...
    "InputVariation","MaximumTrackingError_m","SolverFailures", ...
    "StateViolationCount","MaximumStateViolation","InputViolationCount", ...
    "MaximumInputViolation","RateViolationCount","MaximumRateViolation"];
check_required(all(ismember(required_columns,string(actual.Properties.VariableNames))), ...
    'Generated metrics contain every required verification column.');
check_required(height(actual) == 6 && height(expected) == 6, ...
    'The default workflow contains exactly the six paper runs.');

actual_keys = string(actual.Case) + "|" + string(actual.Method);
expected_keys = string(expected.Case) + "|" + string(expected.Method);
check_required(isequal(actual_keys,expected_keys), ...
    'Case and degree rows match the paper ordering.');
check_close(actual.Coefficients,expected.Coefficients,0, ...
    'Dictionary coefficient counts are 40, 58, and 80.');

for row = 1:height(expected)
    label = char(expected_keys(row));
    if expected.Case(row) == "mass_change"
        check_close(actual.PositionRMSE_m(row),expected.PositionRMSE_m(row),5e-4, ...
            [label ' position RMSE']);
        check_close(actual.FinalMassError_kg(row),expected.FinalMassError_kg(row),5e-4, ...
            [label ' final mass error']);
        check_close(actual.FinalTrimError_N(row),expected.FinalTrimError_N(row),5e-4, ...
            [label ' final trim-thrust error']);
    elseif expected.Case(row) == "helix"
        check_close(actual.PositionRMSE_m(row),expected.PositionRMSE_m(row),5e-5, ...
            [label ' position RMSE']);
        check_close(actual.PredictionPositionRMSE(row),expected.PredictionPositionRMSE(row),5e-7, ...
            [label ' prediction RMSE']);
        check_close(actual.InputVariation(row),expected.InputVariation(row),5e-3, ...
            [label ' input variation']);
        check_close(actual.MaximumTrackingError_m(row),expected.MaximumTrackingError_m(row),5e-5, ...
            [label ' maximum tracking error']);
    else
        error('verify_paper_results:UnexpectedCase', ...
            'Unexpected case "%s" in the expected metrics.',expected.Case(row));
    end
end

check_required(all(actual.SolverFailures == 0), ...
    'All six runs have zero QP solver failures.');
check_required(all(actual.StateViolationCount == 0) && ...
    all(actual.MaximumStateViolation <= 1e-12), ...
    'All six runs have zero state-constraint violations.');
check_required(all(actual.InputViolationCount == 0) && ...
    all(actual.MaximumInputViolation <= 1e-12), ...
    'All six runs have zero input-constraint violations.');
check_required(all(actual.RateViolationCount == 0) && ...
    all(actual.MaximumRateViolation <= 1e-12), ...
    'Input-rate residuals are limited to floating-point roundoff.');

validate_paper_parameters();

fprintf('\nPaper reproduction verification passed.\n');
fprintf('QP timing columns were intentionally excluded as platform-dependent.\n');
end

function validate_paper_parameters()
p = pcac_parameters();

check_close(p.Ts,0.10,1e-14,'Table III sampling period');
check_close(p.N,10,0,'Table III prediction horizon');
check_close(p.m0,4.34,1e-14,'Table III nominal mass');
check_close(p.g,9.81,1e-14,'Table III gravity');
check_close(p.J,diag([0.0820,0.0845,0.1377]),1e-14,'Table III inertia');
check_close(p.m0*p.g,42.5754,1e-12,'Table III nominal hover thrust');
check_close(p.u_min,[0;-2;-2;-1.2],1e-14,'Table III input lower bound');
check_close(p.u_max,[85;2;2;1.2],1e-14,'Table III input upper bound');
check_close(p.du_max,[6;0.35;0.35;0.25],1e-14,'Table III input-increment upper bound');
check_close(p.du_min,-p.du_max,1e-14,'Table III input-increment lower bound');
check_close(p.hx(1:3),[pi;50*pi/180;50*pi/180],1e-14,'Table III attitude bounds');
check_close(diag(p.Q),[110;110;150;2;3;3;18;18;28;0.7;0.7;0.7], ...
    1e-14,'Table III state weight');
check_close(p.Qf,8*p.Q,1e-14,'Table III terminal weight');
check_close(p.R,diag([0.015,0.18,0.18,0.12]),1e-14,'Table III input weight');
check_close(p.S,1e5*eye(6),1e-10,'Table III slack weight');
check_close(p.rls.P0,0.1,1e-14,'Table III initial RLS covariance scale');
check_close([p.rls.tau_n,p.rls.tau_d],[5,25],0,'Table III VRF windows');
check_close(p.rls.eta,0.50,1e-14,'Table III VRF gain');
check_close(p.mass_bounds,[2.5,7.0],1e-14,'Table III mass projection interval');
check_required(strcmpi(p.rls.initialization,'nominal-linear-zoh'), ...
    'RLS uses nominal hover-linear exact-ZOH initialization.');

check_close(p.rk4_substeps,10,0,'Paper RK4 substeps');
check_required(strcmpi(p.qp.algorithm,'active-set'), ...
    'Paper QP algorithm is active-set.');
check_close(p.qp.max_iterations,180,0,'Paper QP iteration limit');
check_close(p.qp.constraint_tolerance,1e-7,1e-20,'Paper QP constraint tolerance');
check_close(p.case1.Tf,28,0,'Paper Case 1 duration');
check_close(p.case1.mass_change_time,13,0,'Paper Case 1 mass-change time');
check_close(p.case1.mass_after,5.60,1e-14,'Paper Case 1 post-change mass');
check_close(p.case2.Tf,21,0,'Paper Case 2 duration');
check_close(p.case2.mass,p.m0,1e-14,'Paper Case 2 constant mass');
check_close(p.case1.x0,zeros(12,1),0,'Paper Case 1 initial state');
check_close(p.case2.x0,zeros(12,1),0,'Paper Case 2 initial state');
check_close(p.case1.u0,p.ue0,1e-14,'Paper Case 1 initial input');
check_close(p.case2.u0,p.ue0,1e-14,'Paper Case 2 initial input');
check_required(~p.measurement_noise.enabled, ...
    'Paper simulations use noise-free measurements.');
check_close([p.case1.disturbance.force_amplitude; ...
             p.case1.disturbance.torque_amplitude; ...
             p.case2.disturbance.force_amplitude; ...
             p.case2.disturbance.torque_amplitude],zeros(12,1),0, ...
    'Paper simulations use zero applied disturbances.');

check_close([p.case1.reference.ramp_time; ...
             p.case1.reference.amplitude_xy; ...
             p.case1.reference.frequency_xy; ...
             p.case1.reference.z_offset; ...
             p.case1.reference.z_amplitude; ...
             p.case1.reference.z_frequency], ...
            [3;0.80;0.60;0.36;0.29;1.00;0.70;0.90],1e-14, ...
    'Paper Case 1 reference parameters');
check_close([p.case2.reference.ramp_time; ...
             p.case2.reference.radius; ...
             p.case2.reference.angular_rate; ...
             p.case2.reference.z_offset; ...
             p.case2.reference.climb_rate; ...
             p.case2.reference.z_amplitude; ...
             p.case2.reference.z_frequency], ...
            [3;1.50;1.50;0.80;0.075;0.22;0.78],1e-14, ...
    'Paper Case 2 reference parameters');

check_required(~p.case1.include_fixed_trim_baseline, ...
    'Unreported fixed-trim baseline is disabled by default.');
check_required(~p.graphics.make_animation, ...
    'Optional animations are disabled by default.');

check_close(p.rls.jitter,1e-12,1e-24,'Implementation RLS covariance jitter');
check_close(p.qp.hessian_regularization,1e-9,1e-21,'Implementation QP Hessian regularization');
check_close(p.euler_min_abs_cos_roll,0.08,1e-14,'Implementation Euler-chart guard');
check_close(p.qp.safety_tolerance,2e-7,1e-20,'Implementation QP safety tolerance');

dictionary_counts = arrayfun(@(D) taylor_dictionary(D).total_coefficients,1:3);
check_close(dictionary_counts,[40,58,80],0,'Paper dictionary sizes');
end

function check_required(condition,label)
if ~all(condition(:))
    error('verify_paper_results:Failed','%s',label);
end
fprintf('[PASS] %s\n',label);
end

function check_close(actual,expected,tolerance,label)
same_size = isequal(size(actual),size(expected));
finite_values = all(isfinite(actual(:))) && all(isfinite(expected(:)));
within_tolerance = same_size && finite_values && ...
    all(abs(actual(:)-expected(:)) <= tolerance);
check_required(within_tolerance,label);
end
